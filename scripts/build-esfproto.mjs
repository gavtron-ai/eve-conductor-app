// STATIC PROTOBUF DECODERS FOR THE FIT CATALOG (v0.224.1) — `npm run build:esfproto`.
//
// Generates src/data/esf/esf.static.js (+ .d.ts) from src/data/esf/esf.proto with protobufjs-cli's
// pbjs/pbts, run transiently through npx (the CLI and its tree are not a dependency of the app).
// Why static code exists: protobufjs' reflection path compiles every decoder from source text at
// runtime, which the page's Content-Security-Policy refuses (audit F3 — the installed 0.224.0
// logged 12 refusals and the fit catalog never loaded). Re-run this whenever esf.proto changes;
// tests/esfstatic.test.cjs proves the static decoders equal the reflection decoders on the real
// .pb2 files.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const APP = path.resolve(import.meta.dirname, '..');
const ESF = path.join(APP, 'src', 'data', 'esf');
const CLI = 'protobufjs-cli@1.2.0';
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const js = path.join(ESF, 'esf.static.js');
const dts = path.join(ESF, 'esf.static.d.ts');

function run(args) {
  const r = spawnSync(npx, ['-y', '-p', CLI, ...args], { cwd: APP, encoding: 'utf8', shell: process.platform === 'win32', stdio: 'inherit' });
  if (r.status !== 0) { console.error(`${args[0]} failed (exit ${r.status})`); process.exit(1); }
}

run(['pbjs', '-t', 'static-module', '-w', 'es6', '--no-create', '--no-encode', '--no-verify', '--no-convert', '--no-delimited', '--no-service', '-o', js, path.join(ESF, 'esf.proto')]);
run(['pbts', '-o', dts, js]);

const header = [
  '// GENERATED by `npm run build:esfproto` (scripts/build-esfproto.mjs → protobufjs-cli pbjs, static-module)',
  '// from esf.proto — DO NOT EDIT; regenerate when esf.proto changes. Static decoders, not reflection,',
  '// because reflection compiles its decoders from source text at runtime and the Content-Security-Policy',
  '// refuses that (v0.224.1). tests/esfstatic.test.cjs proves equality with the reflection decode.',
  '',
].join('\n');
// the schema has no 64-bit field, so pbts' `import Long = require("long")` is dead weight (and a lint error)
const dropLong = (s) => s.split('\n').filter((l) => l !== 'import Long = require("long");').join('\n');
for (const f of [js, dts]) fs.writeFileSync(f, header + dropLong(fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n')));
console.log(`wrote ${path.relative(APP, js)} (${fs.statSync(js).size} bytes) and ${path.relative(APP, dts)} (${fs.statSync(dts).size} bytes)`);
