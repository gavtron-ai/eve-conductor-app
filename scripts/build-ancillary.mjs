// Regenerate src/lib/ancillaryTypes.ts from the bundled CCP type table.
//
// Modules whose CAPACITOR behaviour depends on carrying charges. Needed
// synchronously during render, and typedb.json only carries an inventory
// group for SHIPS — so it is a generated static set rather than a lookup.
//
// BY GROUP, NEVER BY NAME: "Ancillary Current Router" is a RIG, and a name
// match would have silently treated it as an unloaded ancillary module.
import fs from 'node:fs';
import path from 'node:path';
import protobuf from 'protobufjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const ESF = path.join(ROOT, 'src', 'data', 'esf');

const GROUPS = {
  76: 'Capacitor Booster',
  1156: 'Ancillary Shield Booster',
  1199: 'Ancillary Armor Repairer',
  1697: 'Ancillary Remote Shield Booster',
  1698: 'Ancillary Remote Armor Repairer',
};

const root = await protobuf.load(path.join(ESF, 'esf.proto'));
const Types = root.lookupType('Types');
const types = Types.toObject(Types.decode(fs.readFileSync(path.join(ESF, 'types.pb2'))), { longs: Number }).entries ?? {};

const ids = [];
for (const [typeId, t] of Object.entries(types)) {
  if (GROUPS[t.groupID] && !/Blueprint|Mutaplasmid/i.test(t.name ?? '')) ids.push(Number(typeId));
}
ids.sort((a, b) => a - b);

const out = `// MODULES WHOSE CAPACITOR BEHAVIOUR DEPENDS ON CARRYING CHARGES.
//
// GENERATED by scripts/build-ancillary.mjs from CCP's own group table:
${Object.entries(GROUPS).map(([id, n]) => `//   ${id} ${n}`).join('\n')}
//
// BY GROUP, NEVER BY NAME. "Ancillary Current Router" is a RIG — a name match
// would have treated it as an unloaded ancillary module and suppressed a
// genuine capacitor problem.
//
// WHY THIS EXISTS: an Ancillary Shield Booster with no charges drains
// capacitor that a charged one would not touch, and a Capacitor Booster with
// no charges injects nothing. Judging capacitor from an unloaded fit measures
// the loadout, not the fit — so when any of these is empty, the app declines
// to call capacitor broken.
//
// Public EVE data: nothing here is player-specific.

const ANCILLARY = new Set<number>([
${ids.map((i) => `  ${i},`).join('\n')}
]);

/** true when this module only behaves itself with charges loaded */
export const isAncillary = (typeId: number): boolean => ANCILLARY.has(typeId);

export const ANCILLARY_COUNT = ANCILLARY.size;
`;
fs.writeFileSync(path.join(ROOT, 'src', 'lib', 'ancillaryTypes.ts'), out);
console.log(`wrote src/lib/ancillaryTypes.ts — ${ids.length} types`);
