/** every skill relevant to the fit, tiered and explained.
 * fitAttrs = the set of dogma attribute ids present ANYWHERE in the fit
 * (hull + fitted items, from the ESF data bundle). With it, ship/char-wide
 * modifiers only count when the fit actually HAS the attribute they modify —
 * without it (data unavailable) the old, over-inclusive behavior applies:
 * Jump Drive Calibration is not relevant to a ship with no jump drive, and
 * Diplomacy's standings are not part of any fit. */
function relevantForFit(fit, attrsByType) {
    // union across the fit, for ship/char-wide (kind 0/1) checks
    const fitAttrs = attrsByType
        ? new Set([...attrsByType.values()].flatMap((s) => [...s]))
        : undefined;
    /** does THIS item carry the modified attribute? Cross-racial subsystem
     * skills share one dogma group (958 Core Subsystem etc.) and differ only
     * by which subsystemBonus… attribute they write — a Loki must not be
     * told to train Caldari Core Systems. No attr data = keep (inclusive). */
    const itemHasAttr = (typeId, attrId) => attrsByType ? (attrsByType.get(typeId)?.has(attrId) ?? false) : true;
    const map = new Map();
    const touch = (skillId) => {
        const skill = skillById.get(skillId);
        if (!skill)
            return undefined;
        let e = map.get(skillId);
        if (!e) {
            e = { skill, tier: 4, requiredLevel: 0, requiredBy: [], boosts: [] };
            map.set(skillId, e);
        }
        return e;
    };
    const fitTypeIds = [...(fit.shipId !== null ? [fit.shipId] : []), ...fit.items.map((i) => i.typeId)];
    // 1. required skills (direct + full prerequisite closure)
    const needed = new Map();
    const demand = (skillId, level, by) => {
        const cur = needed.get(skillId);
        if (cur) {
            cur.level = Math.max(cur.level, level);
            cur.by.add(by);
        }
        else {
            needed.set(skillId, { level, by: new Set([by]) });
        }
        // prerequisites of the skill itself
        for (const [preId, preLvl] of skillById.get(skillId)?.prereqs ?? []) {
            const pre = needed.get(preId);
            const label = `prerequisite of ${skillById.get(skillId)?.name ?? '?'}`;
            if (!pre)
                demand(preId, preLvl, label);
            else if (preLvl > pre.level) {
                pre.level = preLvl;
                pre.by.add(label);
            }
            else
                pre.by.add(label);
        }
    };
    for (const tid of fitTypeIds) {
        for (const [skillId, level] of reqByType.get(tid) ?? [])
            demand(skillId, level, nameOfType(tid));
    }
    for (const [skillId, info] of needed) {
        const e = touch(skillId);
        if (!e)
            continue;
        e.tier = 1;
        e.requiredLevel = info.level;
        e.requiredBy = [...info.by];
    }
    // 2. hull trait bonuses (per-skill rows on the ship)
    if (fit.shipId !== null) {
        for (const [skillId, bonus, unitId, text] of traitsByShip.get(fit.shipId) ?? []) {
            if (skillId <= 0)
                continue; // role bonus — no skill involved
            const e = touch(skillId);
            if (!e)
                continue;
            if (e.tier > 2)
                e.tier = 2;
            const amount = bonus !== 0 ? `${bonus}${unitId === 105 ? '%' : ''} ` : '';
            e.boosts.push(`${fit.shipName}: ${amount}${text} (per level)`);
        }
    }
    // 3+4. dogma modifiers: which skills touch these items / the ship / everything
    const directReqOf = (tid) => reqByType.get(tid) ?? [];
    const isCharge = (tid) => categoryOfGroup.get(groupOfType.get(tid) ?? -1) === 8;
    for (const [skillId, mods] of modsBySkill) {
        for (const [kind, attrId, extra] of mods) {
            const what = attrName.get(attrId) ?? `attr ${attrId}`;
            if (kind === 2 || kind === 5) {
                // kind 2 (location-required) hits FITTED items — modules, drones;
                // kind 5 (owner-required) hits OWNED items — charges, drones.
                // Citing a launcher for a charge-attribute boost was finding #5.
                const pool = fit.items.filter((i) => (kind === 5 ? isOwnedCategory(i.typeId) : !isCharge(i.typeId)));
                const hit = pool.filter((i) => directReqOf(i.typeId).some(([s]) => s === extra) && itemHasAttr(i.typeId, attrId));
                if (hit.length > 0) {
                    const e = touch(skillId);
                    if (!e)
                        continue;
                    if (e.tier > 3)
                        e.tier = 3;
                    e.boosts.push(`${what} — ${hit.slice(0, 3).map((h) => h.name).join(', ')}${hit.length > 3 ? ` +${hit.length - 3} more` : ''}`);
                }
            }
            else if (kind === 3) {
                const hit = fit.items.filter((i) => groupOfType.get(i.typeId) === extra && itemHasAttr(i.typeId, attrId));
                if (hit.length > 0) {
                    const e = touch(skillId);
                    if (!e)
                        continue;
                    if (e.tier > 3)
                        e.tier = 3;
                    e.boosts.push(`${what} — ${hit.slice(0, 3).map((h) => h.name).join(', ')}${hit.length > 3 ? ` +${hit.length - 3} more` : ''}`);
                }
            }
            else if (kind === 0 || kind === 1) {
                // attributes WITHOUT a CCP display name are the plumbing behind hull
                // traits (shipBonusAB…) — the trait rows already say it in English.
                // A curated few internal attrs ARE real player-facing effects
                // (max active drones, warp cap need) and get English labels here.
                const label = (attrHasDisplay.get(attrId) ?? false) ? what : INTERNAL_ATTR_LABELS[what];
                if (!label)
                    continue;
                if (kind === 0 && fit.shipId === null)
                    continue;
                if (fitAttrs) {
                    // maxActiveDrones exists on the CHARACTER, never on fit items —
                    // it matters exactly when the fit carries drones
                    if (what === 'maxActiveDrones') {
                        const hasDrones = fit.items.some((i) => categoryOfGroup.get(groupOfType.get(i.typeId) ?? -1) === 18);
                        if (!hasDrones)
                            continue;
                    }
                    else if (!fitAttrs.has(attrId)) {
                        // the fit has NO such attribute — this skill moves nothing here
                        continue;
                    }
                }
                const e = touch(skillId);
                if (!e)
                    continue;
                e.boosts.push(`${kind === 0 ? 'ship' : 'character'}: ${label}`);
            }
        }
    }
    return [...map.values()].sort((a, b) => a.tier - b.tier ||
        b.requiredLevel - a.requiredLevel ||
        a.skill.name.localeCompare(b.skill.name));
}
