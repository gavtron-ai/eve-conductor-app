/** skills matching a topic (or free-text keywords), strongest match first */
function resolveTopic(topic, custom) {
    const hits = [];
    const kw = custom.trim().toLowerCase()
        ? custom.trim().toLowerCase().split(/[,\s]+/).filter((w) => w.length >= 3)
        : [];
    for (const s of exports.allSkills) {
        let best = null;
        const consider = (strength, reason) => {
            if (!best || strength < best.strength)
                best = { skill: s, strength, reason };
        };
        if (topic) {
            if (topic.names?.some((n) => n.toLowerCase() === s.name.toLowerCase()))
                consider(0, 'core skill for this topic');
            if (topic.groups?.includes(s.group))
                consider(1, `${s.group} skill group`);
            for (const k of topic.keywords ?? []) {
                if (s.name.toLowerCase().includes(k))
                    consider(2, `name matches “${k}”`);
                else if (s.desc.toLowerCase().includes(k))
                    consider(3, `description mentions “${k}”`);
            }
        }
        for (const k of kw) {
            if (s.name.toLowerCase().includes(k))
                consider(2, `name matches “${k}”`);
            else if (s.desc.toLowerCase().includes(k))
                consider(3, `description mentions “${k}”`);
        }
        if (best)
            hits.push(best);
    }
    return hits.sort((a, b) => a.strength - b.strength || a.skill.name.localeCompare(b.skill.name));
}
