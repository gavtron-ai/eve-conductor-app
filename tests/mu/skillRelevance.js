/**
 * Parse the EVE client's "Copy to Clipboard" fit format (EFT):
 *   [Hull, fit name]
 *   Module Name
 *   Module Name, Charge Name
 *   [Empty Med slot]
 *   Drone Name x5
 * Unresolvable lines are REPORTED, never silently dropped.
 */
function parseFit(text) {
    const out = { shipId: null, shipName: '', fitName: '', items: [], unresolved: [], extraFits: 0 };
    const counts = new Map();
    const resolve = (name) => {
        // "/OFFLINE" can trail the MODULE segment mid-line ("Launcher /OFFLINE,
        // Charge") as well as the whole line — strip it wherever it lands
        const clean = name.replace(/\s*\/offline$/i, '').trim();
        const t = (0, typedb_1.findByName)(clean);
        if (t)
            return { id: t.id, name: t.name };
        // abyssal/mutated bases, civilian modules, boosters: not on the market
        // (absent from typedb) but their skill requirements are real
        return extraByName.get(clean.toLowerCase());
    };
    const addItem = (name, qty, offline = false) => {
        const t = resolve(name);
        if (!t)
            return false;
        const cur = counts.get(t.id);
        if (cur) {
            cur.qty += qty;
            if (offline)
                cur.offlineQty += qty;
        }
        else {
            counts.set(t.id, { typeId: t.id, name: t.name, qty, charges: [], offlineQty: offline ? qty : 0 });
        }
        return true;
    };
    let headerDone = false;
    for (const rawLine of text.split(/\r?\n/)) {
        // "/OFFLINE" marks a module fitted but offline (pyfa emits it, the EVE
        // client accepts it) — the module is still on the ship, skills and all,
        // but it draws no CPU/PG/cap, so the flag must survive into the item
        const isOffline = /\/offline\b/i.test(rawLine);
        const line = rawLine.trim().replace(/\s*\/offline$/i, '');
        if (!line)
            continue;
        if (headerDone && line.startsWith('[') && line.endsWith(']') && !/^\[empty .* slot\]$/i.test(line)) {
            // a SECOND fit header: analyzing a merged pile of two fits would lie
            // about both — stop here and say so
            out.extraFits += 1;
            break;
        }
        if (!headerDone && line.startsWith('[') && line.endsWith(']')) {
            headerDone = true;
            const inner = line.slice(1, -1);
            const comma = inner.indexOf(',');
            const hullName = (comma === -1 ? inner : inner.slice(0, comma)).trim();
            out.fitName = comma === -1 ? '' : inner.slice(comma + 1).trim();
            const hull = (0, typedb_1.findByName)(hullName);
            if (hull) {
                out.shipId = hull.id;
                out.shipName = hull.name;
            }
            else {
                out.shipName = hullName;
                out.unresolved.push(`${hullName} (hull)`);
            }
            continue;
        }
        if (/^\[empty .* slot\]$/i.test(line))
            continue;
        // "Module, Charge" — try the full line first (some names contain commas)
        if (addItem(line.replace(/\s+x\d+$/i, ''), 1, isOffline)) {
            const m = line.match(/\s+x(\d+)$/i);
            if (m) {
                // re-add with the real quantity (addItem above put qty 1)
                const t = resolve(line.replace(/\s+x\d+$/i, ''));
                const entry = counts.get(t.id);
                entry.qty += Number(m[1]) - 1;
                if (isOffline)
                    entry.offlineQty += Number(m[1]) - 1;
            }
            continue;
        }
        const comma = line.lastIndexOf(',');
        if (comma !== -1) {
            const mod = line.slice(0, comma).trim();
            const charge = line.slice(comma + 1).trim();
            const okMod = addItem(mod, 1, isOffline);
            const okCharge = addItem(charge, 1);
            if (okMod || okCharge) {
                if (!okMod)
                    out.unresolved.push(mod);
                if (!okCharge)
                    out.unresolved.push(charge);
                if (okMod && okCharge) {
                    // one entry per LOADED COPY — split ammo across a stack keeps
                    // each copy's own charge
                    counts.get(resolve(mod).id).charges.push(resolve(charge).id);
                }
                continue;
            }
        }
        const qtyMatch = line.match(/^(.*?)\s+x(\d+)$/i);
        if (qtyMatch && addItem(qtyMatch[1].trim(), Number(qtyMatch[2]), isOffline))
            continue;
        out.unresolved.push(line);
    }
    out.items = [...counts.values()];
    return out;
}
