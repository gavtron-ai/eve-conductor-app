/** EVE's unit CONVERSIONS — the raw dogma number is not what the game
 * shows. 108 inverse-absolute-% stores a resonance (0.4 → "60%" resist),
 * 127 absolute-% is a fraction, 105/109/111/124 modifier-% are multipliers
 * around 1 (1.05 → "+5%"). Verified against eveUnits + a live engine run. */
function formatAttrValue(value, unitId) {
    const round = (n) => (Math.abs(n) >= 1000 ? n.toFixed(0) : Math.abs(n) >= 10 ? n.toFixed(1) : n.toFixed(2));
    switch (unitId) {
        case 108: // inverse absolute percent (resonances)
            return `${round((1 - value) * 100)} %`;
        case 127: // absolute percent
            return `${round(value * 100)} %`;
        case 105:
        case 109:
        case 111:
        case 124: // modifier percent (multiplier around 1)
            return `${value >= 1 ? '+' : ''}${round((value - 1) * 100)} %`;
        default: {
            const unit = unitNames.get(unitId) ?? '';
            return `${round(value)}${unit ? ` ${unit}` : ''}`;
        }
    }
}
